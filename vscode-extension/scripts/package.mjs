import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import process from "node:process";

const target = process.argv[2];
if (!target) throw new Error("Usage: node scripts/package.mjs <linux-x64|darwin-arm64|darwin-x64|win32-x64>");
const extensionRoot = resolve(".");
const packageManifest = JSON.parse(readFileSync(join(extensionRoot, "package.json"), "utf8"));
const pythonVersionSource = readFileSync(join(extensionRoot, "../src/open_code_agent/__init__.py"), "utf8");
const pythonVersion = pythonVersionSource.match(/__version__\s*=\s*["']([^"']+)["']/)?.[1];
if (!pythonVersion || packageManifest.version !== pythonVersion) throw new Error(`Extension version ${packageManifest.version} does not match runtime version ${pythonVersion ?? "unknown"}.`);
const stage = resolve(".package-stage");
const outDir = resolve("../artifacts");
mkdirSync(outDir, { recursive: true });
const out = resolve(outDir, `open-code-agent-${target}.vsix`);
const runtimeName = target.startsWith("win32-") ? "open-code-agent.exe" : "open-code-agent";
if (!existsSync(join(extensionRoot, "runtime", target, runtimeName))) throw new Error(`Missing native runtime ${target}; run build:runtime on its matching OS and architecture first.`);
rmSync(stage, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });
for (const name of ["dist", "media"]) cpSync(join(extensionRoot, name), join(stage, name), { recursive: true });
cpSync(join(extensionRoot, "../LICENSE"), join(stage, "LICENSE"));
cpSync(join(extensionRoot, "../README.md"), join(stage, "README.md"));
cpSync(join(extensionRoot, "runtime", target), join(stage, "runtime", target), { recursive: true });
const manifest = packageManifest;
delete manifest.private;
writeFileSync(join(stage, "package.json"), JSON.stringify(manifest, null, 2) + "\n");
writeFileSync(join(stage, ".vscodeignore"), ".vscode/**\nsrc/**\ntest/**\nscripts/**\n*.ts\ntsconfig.json\neslint.config.js\n");
const npm = process.platform === "win32" ? "npm.cmd" : "npm";
const result = spawnSync(npm, ["exec", "--yes", "--package", "@vscode/vsce@3.2.1", "--", "vsce", "package", "--target", target, "--out", out], { cwd: stage, stdio: "inherit", shell: false });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
rmSync(stage, { recursive: true, force: true });
const verify = spawnSync(process.execPath, ["scripts/verify-package.mjs", out, target], { cwd: extensionRoot, stdio: "inherit", shell: false });
if (verify.error) throw verify.error;
if (verify.status !== 0) process.exit(verify.status ?? 1);
