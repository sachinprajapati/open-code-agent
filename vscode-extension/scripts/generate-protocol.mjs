import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const manifestPath = resolve(import.meta.dirname, "../../docs/app-server.protocol.json");
const outputPath = resolve(import.meta.dirname, "../src/runtime/protocol.generated.ts");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const literals = (items) => items.map((item) => JSON.stringify(item.name)).join(" | ");
const capability = manifest.capabilities.map((name) => `  ${JSON.stringify(name)}: true,`).join("\n");
const source = `/* This file is generated by scripts/generate-protocol.mjs. Do not edit. */\n` +
  `export const PROTOCOL_VERSION = ${JSON.stringify(manifest.protocol_version)} as const;\n` +
  `export const CLIENT_METHODS = [${manifest.methods.filter((item) => item.direction === "client_to_server").map((item) => JSON.stringify(item.name)).join(", ")}] as const;\n` +
  `export const SERVER_REQUESTS = [${manifest.methods.filter((item) => item.direction === "server_to_client").map((item) => JSON.stringify(item.name)).join(", ")}] as const;\n` +
  `export const SERVER_NOTIFICATIONS = [${manifest.notifications.filter((item) => item.direction === "server_to_client").map((item) => JSON.stringify(item.name)).join(", ")}] as const;\n` +
  `export type ClientMethod = ${literals(manifest.methods.filter((item) => item.direction === "client_to_server"))};\n` +
  `export type ServerRequest = ${literals(manifest.methods.filter((item) => item.direction === "server_to_client"))};\n` +
  `export type ServerNotification = ${literals(manifest.notifications.filter((item) => item.direction === "server_to_client"))};\n` +
  `export const REQUIRED_CAPABILITIES = {\n${capability}\n} as const;\n`;
if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== source) { console.error("Generated protocol types are stale. Run npm run protocol:generate."); process.exitCode = 1; }
} else await writeFile(outputPath, source);
